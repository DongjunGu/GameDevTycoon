// AlertUI 통합 문구에서 문장 중간에 아이콘+배경(pill)으로 끼워넣는 항목 종류.
// b1~b8 목업 기준 분류 — None(순수 텍스트)/Money는 라벨 없이 아이콘만, 나머지는 아이콘+고정 라벨이
// 하나의 이미지로 이미 합쳐져 있는 것을 그대로 인라인으로 삽입한다. Item만 이름이 매번 달라 라벨을
// 이미지에 못 넣으므로 아이콘만 pill로 넣고 이름은 그 뒤에 일반 텍스트로 붙인다.
public enum AlertPillCategory
{
    None,
    Satisfaction,  // 만족도 — 하트 아이콘 + "만족도" 라벨
    Ability,       // 능력치 버프/디버프 — 톱니바퀴 아이콘 + "능력치" 라벨
    DevPeriod,     // 개발기간 — 시계 아이콘 + "개발 기간" 라벨
    Planning,      // 기획 점수 — 기획 아이콘 + "기획" 라벨
    Programmer,    // 개발 점수 — 개발 아이콘 + "개발" 라벨
    Artist,        // 아트 점수 — 아트 아이콘 + "아트" 라벨
    Creativity,    // 창의성 점수 — 창의성 아이콘 + "창의성" 라벨
    Money,         // 연봉/금액 — 코인 아이콘만(라벨 없음)
    Item,          // 아이템 획득 — 아이템별 아이콘만(라벨 없음, 이름은 별도 텍스트)
}
